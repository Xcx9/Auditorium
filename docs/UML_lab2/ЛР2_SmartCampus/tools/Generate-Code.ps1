$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent

# Генератор понимает только используемое в этой работе подмножество PlantUML:
# class Name { ... }, свойства + Name : Type и методы + Name() : Type.
# Он читает диаграмму, а не копирует заранее заготовленные классы.
function Convert-DiagramToCSharp($source, $destination, $namespace) {
    $text = Get-Content -LiteralPath $source -Raw -Encoding UTF8
    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.Add('// <auto-generated> Generated from the PlantUML class diagram. </auto-generated>')
    $lines.Add('using System;')
    $lines.Add('using System.Collections.Generic;')
    $lines.Add("namespace $namespace;")
    $classes = [regex]::Matches($text, '(?ms)^class (\w+)\s*\{(.*?)^\}')
    if ($classes.Count -eq 0) { throw "No classes in $source" }
    foreach ($class in $classes) {
        $lines.Add("public class $($class.Groups[1].Value)")
        $lines.Add('{')
        foreach ($member in ($class.Groups[2].Value -split '\r?\n')) {
            if ($member -match '^\s*\+\s*(/)?(\w+)\s*:\s*(.+?)\s*$') {
                $derived = $Matches[1]
                $name = $Matches[2]
                $type = $Matches[3]
                if ($derived) {
                    $lines.Add('    // Производное поле Room: пересчитывается сервисом перед выдачей.')
                    $lines.Add("    public $type $name { get; internal set; }")
                } else {
                    $lines.Add("    public $type $name { get; set; }")
                }
            } elseif ($member -match '^\s*\+\s*(\w+)\(\)\s*:\s*(\w+)\s*$') {
                $lines.Add("    public $($Matches[2]) $($Matches[1])() => throw new NotImplementedException();")
            } elseif ($member.Trim()) {
                throw "Unsupported member: $member"
            }
        }
        $lines.Add('}')
    }
    $lines | Set-Content -LiteralPath $destination -Encoding UTF8
    Write-Output "Generated $($classes.Count) classes: $destination"
}
